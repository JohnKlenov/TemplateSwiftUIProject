// DATA REFRESH ARCHITECTURE
// ================================================================
//
// Задача:
// Держать единый источник истины о том, когда данные Droplist
// были обновлены, и понимать, какие экраны уже видели это обновление.
//
// ---------------------------------------------------------------
// 1. DataRefreshStateStore — единая точка состояния
// ---------------------------------------------------------------
//
// Store живёт столько же, сколько общий DropListDataSource,
// поэтому его состояние НЕ уничтожается вместе с View / ViewModel.
//
// Store хранит:
//
//     lastUpdated
//     revision
//
// lastUpdated — время последнего успешного обновления Droplist.
//
// revision — номер версии данных.
// При каждом успешном обновлении revision увеличивается:
//
//     revision 1 → revision 2 → revision 3 → ...
//
// Важно:
// lastUpdated отвечает на вопрос:
// "Когда данные обновлялись?"
//
// revision отвечает на вопрос:
// "Изменились ли данные с тех пор, как конкретный экран
// последний раз их видел?"
//
// ---------------------------------------------------------------
// 2. Первая запись
// ---------------------------------------------------------------
//
// При первом успешном:
//
//     fetchDataDroplist()
//
// мы фиксируем:
//
//     lastUpdated = Date()
//     revision += 1
//
// Это является начальной точкой жизни данных.
//
// При ошибке initial load:
//
//     lastUpdated = nil
//
// revision при этом НЕ увеличивается,
// потому что новые данные фактически не были получены.
//
// ---------------------------------------------------------------
// 3. Soft Refresh
// ---------------------------------------------------------------
//
// При успешном:
//
//     refreshDropList()
//
// снова выполняется:
//
//     lastUpdated = Date()
//     revision += 1
//
// Таким образом все экраны приложения получают новый revision.
//
// Например:
//
//     Droplist → revision 5
//
// пользователь переходит на Tracklist:
//
//     Tracklist lastSeenRevision = 5
//
// затем Droplist обновляется:
//
//     revision = 6
//
// теперь Tracklist знает, что появились более свежие данные.
//
// ---------------------------------------------------------------
// 4. Почему одного lastUpdated недостаточно
// ---------------------------------------------------------------
//
// Нельзя просто проверять:
//
//     Date().timeIntervalSince(lastUpdated)
//
//
//
// Потому что это отвечает только на вопрос:
// "Сколько времени прошло?"
//
// Например:
//
//     Droplist обновился
//     lastUpdated = 10:00
//
//     Tracklist открылся в 10:10
//
//     прошло 10 минут
//
// Если autoRefreshThreshold = 2 часа,
// Tracklist решит:
//
//     "Данные свежие, сеть не нужна."
//
// Но проблема возникает, если Tracklist уже был открыт раньше,
// например:
//
//     Tracklist увидел revision 5
//
//     пользователь вернулся на Droplist
//
//     Droplist обновился → revision 6
//
//     пользователь снова открыл Tracklist
//
// Здесь время само по себе ничего не говорит о том,
// видел ли Tracklist новую версию данных.
//
// Поэтому используется revision.
//
// ---------------------------------------------------------------
// 5. lastSeenRevision хранится НЕ в TracklistViewModel
// ---------------------------------------------------------------
//
// TracklistViewModel живёт только пока существует экран.
//
// При:
//
//     Back
//
// TracklistViewModel уничтожается.
//
// При следующем входе:
//
//     создаётся новый TracklistViewModel
//
// Поэтому:
//
//     private var lastSeenRevision: Int?
//
// внутри TracklistViewModel использовать нельзя.
//
// Иначе после каждого нового входа:
//
//     lastSeenRevision = nil
//
// и экран потеряет информацию о том,
// какую версию данных он уже видел.
//
// Поэтому lastSeenRevision хранится в общем:
//
//     DataRefreshStateStore
//
// но отдельно для каждого Tracklist.
//
// Например:
//
//     allTracks      → revision 5
//     topDrops       → revision 3
//     droplist       → revision 6
//
// Это позволяет каждому экрану иметь собственную
// "последнюю увиденную версию".
//
// ---------------------------------------------------------------
// 6. Что происходит при открытии Tracklist
// ---------------------------------------------------------------
//
// TracklistViewModel вызывает:
//
//     fetchData()
//
// Сначала проверяем cache.
//
//
//
// CASE 1 — cache отсутствует
//
//     Cache = nil
//
// → идём в сеть
// → получаем данные
// → сохраняем данные в cache
// → запоминаем текущий revision как lastSeenRevision
//
//
//
// CASE 2 — cache существует
//
// Сначала показываем cache.
//
// Затем сравниваем:
//
//     currentRevision
//
//     lastSeenRevision(for: trackType)
//
//
//
// Если:
//
//     currentRevision == lastSeenRevision
//
// значит этот экран уже видел текущую версию данных.
//
// Сеть НЕ нужна.
//
//
//
// Если:
//
//     currentRevision > lastSeenRevision
//
// значит Droplist обновился после последнего посещения
// этого экрана.
//
// В этом случае cache уже потенциально устарел:
//
// → идём в сеть
// → получаем свежую первую страницу
// → обновляем cache
// → записываем новый lastSeenRevision
//
// ---------------------------------------------------------------
// 7. UX
// ---------------------------------------------------------------
//
// Благодаря этому получаем:
//
//     Tracklist opened
//             │
//             ▼
//        Cache exists?
//          /       \
//        NO         YES
//        │           │
//     Network     Show cache
//        │           │
//        │      Revision changed?
//        │         /       \
//        │       NO         YES
//        │       │           │
//        │    Keep cache   Network
//        │                   │
//        └───────────────────┘
//                    │
//             Update cache + UI
//
// То есть пользователь максимально быстро получает
// уже загруженные данные из cache,
// но при этом не теряет новые данные,
// которые появились после предыдущего посещения экрана.
//
// ---------------------------------------------------------------
// 8. DroplistContentView остаётся точкой обновления
// ---------------------------------------------------------------
//
// Только DroplistContentView решает,
// когда пора делать автоматический refresh:
//
//     checkAndRefreshIfNeeded()
//
// Если:
//
//     elapsed > autoRefreshThreshold
//
// выполняется:
//
//     refreshDropList()
//
// При успешном refresh:
//
//     lastUpdated = Date()
//     revision += 1
//
// Таким образом мы НЕ заставляем каждый экран самостоятельно
// проверять таймер и инициировать refresh Droplist.
//
// У нас существует одна точка принятия решения:
//
//     DroplistContentView
//
// А остальные экраны только реагируют на изменение revision.
//
// ---------------------------------------------------------------
// 9. Важный принцип
// ---------------------------------------------------------------
//
// lastUpdated отвечает за TIME.
//
// revision отвечает за VERSION.
//
// lastSeenRevision отвечает за то,
// какую VERSION конкретный экран уже видел.
//
// Поэтому:
//
//     lastUpdated
//          ↓
//     когда обновились данные
//
//     revision
//          ↓
//     какая сейчас версия данных
//
//     lastSeenRevision[screen]
//
//          ↓
//     какую версию видел конкретный экран
//
// ---------------------------------------------------------------
// Итог:
//
// DroplistContentView
//        │
//        │ successful refresh
//        ▼
// DataRefreshStateStore
//        │
//        ├── lastUpdated
//        ├── revision
//        └── lastSeenRevision[screen]
//                    │
//          ┌─────────┼─────────┐
//          ▼         ▼         ▼
//      Droplist   AllTracks  TopDrops
//
// Все экраны используют один общий источник состояния,
// но каждый экран самостоятельно помнит,
// какую версию данных он уже видел.
//
// Это позволяет одновременно получить:
// - быстрый cache-first UX;
// - автоматическое обновление по таймеру;
// - обнаружение изменений между посещениями экранов;
// - отсутствие лишних сетевых запросов;
// - сохранение состояния между уничтожением ViewModel;
// - единую точку управления refresh.
// ================================================================


import Foundation

actor DataRefreshStateStore {

    private var lastUpdated: Date?
    private var revision: Int = 0
    private var lastSeenRevision: [String: Int] = [:]

    func markUpdated() {
        revision += 1
        lastUpdated = Date()
    }

    func reset() {
        lastUpdated = nil
        revision += 1
        lastSeenRevision.removeAll()
    }

    func needsRefresh(for key: String) -> Bool {
        lastSeenRevision[key] != revision
    }

    func markSeen(for key: String) {
        lastSeenRevision[key] = revision
    }

    func currentLastUpdated() -> Date? {
        lastUpdated
    }

    func currentRevision() -> Int {
        revision
    }
}
