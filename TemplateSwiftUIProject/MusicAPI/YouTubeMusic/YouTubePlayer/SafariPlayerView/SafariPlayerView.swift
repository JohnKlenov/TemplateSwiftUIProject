// ================================================================
// YOUTUBE PLAYER STRATEGY (как возможный вариант но он пока костыльный)
// ================================================================
//
// WKWebView — основной embedded player.
//
// Если YouTube показывает anti-bot / verification экран,
// переключаемся на SFSafariViewController:
//
// 1. Закрываем WKWebView.
// 2. Открываем тот же videoId через Safari VC.
// 3. Загружаем обычный:
//    https://www.youtube.com/watch?v=...
//
// Определение anti-bot делаем best-effort: можем искать известный
// текст страницы и анализировать ошибки/состояние WebView.
//
// Важно: YouTube может изменить текст, язык или HTML страницы,
// поэтому поиск конкретной фразы НЕ является 100% надёжным.
// Не строим всю логику только на этом детекторе.
//
// WKWebView → основной embedded player
// SFSafariViewController → fallback для проблемных случаев
//
// Не переключаемся на Safari при любой ошибке видео.
// ================================================================






//
//  🎵 MusicKit + Apple Music: Альтернатива YouTube API
//  ======================================================
//  📌 СУТЬ:
//  MusicKit — это официальный SDK от Apple, который позволяет
//  встраивать каталог Apple Music в своё приложение.
//
//  ✅ ЧТО ДАЁТ:
//  • Полноценный СВОЙ плеер внутри приложения
//  • Фоновое воспроизведение (всегда, если есть подписка)
//  • Доступ к каталогу из 100+ млн треков
//  • Легально, бесплатно для разработчика
//  • Нативная интеграция с iOS (Lock Screen, CarPlay, Siri)
//
//  ❌ ЧТО НУЖНО ОТ ПОЛЬЗОВАТЕЛЯ:
//  • Авторизация через Apple ID (обязательно)
//  • Активная подписка Apple Music (для прослушивания полных треков)
//    Без подписки — только превью (30–90 сек)
//
//  ⚠️ ВАЖНО:
//  В отличие от YouTube API, MusicKit НЕ даёт доступ к музыке
//  бесплатно. Это инструмент для интеграции с подписным сервисом.
//  Однако он даёт ПОЛНЫЙ КОНТРОЛЬ над интерфейсом плеера.
//
//  🆚 СРАВНЕНИЕ С ТЕКУЩИМ РЕШЕНИЕМ (YouTube + WebView):
//  ┌────────────────────┬─────────────────────┬─────────────────────┐
//  │ Критерий           │ YouTube + WebView    │ MusicKit            │
//  ├────────────────────┼─────────────────────┼─────────────────────┤
//  │ Свой плеер         │ ❌ Чужой (iframe)    │ ✅ Да               │
//  │ Фоновое воспр-ние  │ ❌ (только Premium)  │ ✅ Да               │
//  │ Авторизация        │ ❌ Не требуется      │ ✅ Apple ID         │
//  │ Подписка           │ ❌ Не требуется      │ ✅ Apple Music      │
//  │ Каталог            │ ✅ Весь YouTube      │ ✅ Весь Apple Music │
//  │ Стоимость          │ ✅ Бесплатно         │ ✅ Бесплатно        │
//  └────────────────────┴─────────────────────┴─────────────────────┘
//
//  💡 КОГДА ВЫБИРАТЬ MUSICKIT:
//  • Ты хочешь полностью кастомизировать интерфейс плеера
//  • Тебе критично фоновое воспроизведение (всегда)
//  • Твоя целевая аудитория — владельцы iPhone с подпиской Apple Music
//
//  💡 КОГДА ОСТАВАТЬ YOUTUBE + WEBVIEW:
//  • Ты хочешь, чтобы музыка была доступна БЕЗ входа в аккаунт
//  • Ты хочешь охватить пользователей БЕЗ подписки Apple Music
//  • Ты готов мириться с чужим плеером и отсутствием фона
//
//  🔧 БАЗОВАЯ РЕАЛИЗАЦИЯ:
//  1. Запроси доступ: MusicAuthorization.request()
//  2. Проверь подписку: MusicSubscription.current.canPlayCatalogContent
//  3. Ищи треки: MusicCatalogSearchRequest(term: "Kodak Black", types: [.songs])
//  4. Воспроизводи: ApplicationMusicPlayer.shared.queue = [song]
//  5. Запусти: try await ApplicationMusicPlayer.shared.play()
//
//  📌 ИТОГ:
//  MusicKit — это путь к ПРЕМИАЛЬНОМУ пользовательскому опыту
//  за счёт эксклюзивности (только для подписчиков Apple Music).
//  YouTube + WebView — универсальный и бесплатный путь,
//  но с ограничениями по UX.
//  Выбор зависит от твоей целевой аудитории.
